#!/usr/bin/env python3
"""A16 -- evidence-linked agent-attack results table.

Pattern: clean, naive, defense and proposed rows; ASR, benign utility and
detection columns carry direction arrows. The arrays are synthetic placeholders;
real tables must be generated from trials and linked to EVIDENCE IDs.
"""
import sys, pathlib, shutil, subprocess, tempfile
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "style"))
import palette as P

COLS = [("ASR (\\%)", "max", 1), ("Utility (\\%)", "max", 1), ("Detect (\\%)", "min", 1)]
ROWS = [
    ("Clean", [0.0, 100.0, 0.0]),
    ("Naive injection", [24.0, 91.0, 38.0]),
    ("Static defense", [13.0, 86.0, 82.0]),
    ("Proposed attack", [51.0, 89.0, 44.0]),
]


def fmt_table(rows=ROWS, cols=COLS, ref=0):
    arrows = {"min": r"$\downarrow$", "max": r"$\uparrow$"}
    out = [r"\begin{tabular}{l" + "r" * len(cols) + "}", r"\toprule",
           "Arm & " + " & ".join(f"{c} {arrows[d]}" for c, d, _ in cols) + r" \\", r"\midrule"]
    ranks = []
    for j, (_, direction, _) in enumerate(cols):
        values = sorted({row[1][j] for row in rows if row[1][j] is not None}, reverse=(direction == "max"))
        ranks.append(values[:2])
    for i, (name, values) in enumerate(rows):
        if i == len(rows) - 1:
            out.append(r"\midrule")
        cells = []
        for j, value in enumerate(values):
            if value is None:
                cells.append("--")
                continue
            cell = f"{value:.{cols[j][2]}f}"
            if value == ranks[j][0]:
                cell = r"\textbf{" + cell + "}"
            elif len(ranks[j]) > 1 and value == ranks[j][1]:
                cell = r"\underline{" + cell + "}"
            cells.append(cell)
        out.append(f"{name} & " + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out)


def make(venue="lncs", outdir=ROOT / "examples"):
    outdir = pathlib.Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    body = fmt_table()
    frag = outdir / "p16_results_table.tex"
    frag.write_text("% generated by p16_results_table.py -- SYNTHETIC\n" + body + "\n")
    paths = [frag]
    if shutil.which("pdflatex"):
        font = {"lncs": r"\usepackage{lmodern}", "acm": r"\usepackage{newtxtext,newtxmath}",
                "ieee": r"\usepackage{newtxtext,newtxmath}"}[venue]
        doc = (r"\documentclass[border=2pt,10pt]{standalone}" "\n" r"\usepackage[T1]{fontenc}" + font +
               "\n" r"\usepackage{booktabs}" "\n" r"\begin{document}" "\n" + body + "\n" r"\end{document}" "\n")
        with tempfile.TemporaryDirectory() as d:
            (pathlib.Path(d) / "t.tex").write_text(doc)
            subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "t.tex"], cwd=d,
                           check=True, stdout=subprocess.DEVNULL)
            shutil.copy(pathlib.Path(d) / "t.pdf", outdir / "p16_results_table.pdf")
        paths.append(outdir / "p16_results_table.pdf")
        if shutil.which("pdftoppm"):
            subprocess.run(["pdftoppm", "-png", "-r", "300", "-singlefile", str(outdir / "p16_results_table.pdf"),
                            str(outdir / "p16_results_table")], check=True)
            paths.append(outdir / "p16_results_table.png")
    return paths


if __name__ == "__main__":
    t = fmt_table()
    assert r"\textbf{51.0}" in t and r"\underline{24.0}" in t and r"\textbf{100.0}" in t, t
    P.cli(make, __doc__)
